METRO_C = "#c44e52"
QUANTUM_C = "#4c72b0"
EXACT_C = "#2e2e2e"
BASE_COLORS = {"strength": "#55a868", "eigenvector": "#8172b3",
               "debtrank": "#ccb974", "load": "#64b5cd"}
TIER_COLORS = {"core": "#d1495b", "intermediate": "#edae49", "periphery": "#66a182",
               "hub": "#d1495b", "arterial": "#edae49", "local": "#66a182"}


def load():
    import sys
    from pathlib import Path
    here = Path(__file__).resolve().parent
    if str(here) not in sys.path:
        sys.path.insert(0, str(here))
    from py import scenarios_data
    return scenarios_data.load()


# ------------------------------------------------------------- helpers

def steps_to_good(curve, rho_good=0.9, err_good=0.1):
    for c in curve:
        if c["mu_spearman"] >= rho_good and c["chi_relerr"] <= err_good:
            return c["steps"]
    return None


def fmt_steps(s):
    return "never" if s is None else f"{s:,}"


def _show(fig, live=False):
    import matplotlib.pyplot as plt
    fig.tight_layout()
    plt.show()
    plt.close(fig)


def _edge_pairs(p):
    """[(i, j, |A_ij|)] from the digest's sparse edge list."""
    return [(int(i), int(j), float(w)) for i, j, w in p["edges"]]


# ------------------------------------------------------------- figures

def fig_network(p, live=False):
    """Network map, coloured by tier, sized by exact mu, bailout seeds marked."""
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    pos = np.asarray(p["positions"], float)
    n = len(pos)
    tiers = p["tiers"]
    mu = None
    if p.get("exact"):
        mu = np.asarray(p["exact"]["chi"], float).mean(axis=0)
        span = max(mu.max() - mu.min(), 1e-9)
        size = 140 + 1600 * np.clip((mu - mu.min()) / span, 0, 1)
    else:
        size = np.full(n, 300.0)
    colors = [TIER_COLORS.get(t, "#999") for t in tiers]

    fig, ax = plt.subplots(figsize=(7, 4.6))
    for i, j, w in _edge_pairs(p):
        ax.plot([pos[i, 0], pos[j, 0]], [pos[i, 1], pos[j, 1]],
                color="#b8c2cc", lw=0.4 + 2.2 * w, zorder=1, alpha=0.6)
    seeds = set(p["cascade"]["seeds"])
    for i in range(n):
        ax.scatter(*pos[i], s=size[i], color=colors[i],
                   edgecolor="#d1495b" if i in seeds else "#22333b",
                   linewidth=2.2 if i in seeds else 0.8, zorder=3)
        ax.annotate(str(i), pos[i], fontsize=7, ha="center", va="center",
                    color="white", zorder=4, fontweight="bold")
    if mu is not None:
        top = np.argsort(-mu)[: p["spec"]["budget"]]
        for i in top:
            ax.annotate("Q", (pos[i, 0], pos[i, 1] + 0.07), color=QUANTUM_C,
                        fontsize=9, fontweight="bold", ha="center", zorder=5)
    handles = [Line2D([], [], marker="o", ls="", color=c, label=t,
                      markersize=9) for t, c in TIER_COLORS.items()
               if t in set(tiers)]
    handles.append(Line2D([], [], marker="o", ls="", mfc="white",
                          mec="#d1495b", markersize=9, label="cascade seed"))
    ax.legend(handles=handles, loc="upper left", fontsize=7, frameon=False)
    pad = 0.16  # keep big edge nodes from clipping
    ax.set_xlim(pos[:, 0].min() - pad, pos[:, 0].max() + pad)
    ax.set_ylim(pos[:, 1].min() - pad, pos[:, 1].max() + pad)
    ax.set_title(f"{p['spec']['title']}: network map\nnode size = exact "
                 f"susceptibility, Q = quantum top pick", fontsize=10)
    ax.set_axis_off()
    _show(fig, live)


def fig_basins(p, live=False):
    """Where does each sampler actually spend its time?"""
    import matplotlib.pyplot as plt
    n = len(p["tiers"])
    edges = np.linspace(-1.0 - 0.5 / n, 1.0 + 0.5 / n, n + 2)
    centers = (edges[:-1] + edges[1:]) / 2
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.4), sharey=True)
    for ax, arm, color, label in (
        (axes[0], "metro", METRO_C, "Classical MH"),
        (axes[1], "quantum", QUANTUM_C, "QeMCMC"),
    ):
        h = np.asarray(p["arms"][arm]["mag_hist"], float)
        h = h / h.sum() * 100
        ax.bar(centers, h, width=2.1 / n, color=color, alpha=0.85)
        ax.set_title(f"{label}  (acceptance "
                     f"{p['arms'][arm]['acceptance']:.2f}, longest stall "
                     f"{p['arms'][arm]['max_stall']:,} steps)", fontsize=9)
        ax.set_xlabel("magnetization (fraction of healthy spins)")
    axes[0].set_ylabel("% of sampled states")
    if p.get("exact"):
        m = p["exact"]["m"]
        for ax in axes:
            ax.axvline(m, color=EXACT_C, ls="--", lw=1.2)
            ax.annotate(f"exact m={m:+.2f}", (m, ax.get_ylim()[1] * 0.9),
                        fontsize=8, ha="center")
    fig.suptitle(f"{p['spec']['title']}: which basins does each sampler visit?",
                 fontsize=11)
    _show(fig, live)


def fig_traces(p, live=False):
    """Per-chain energy + magnetization traces: the freezing story in one look."""
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(2, 2, figsize=(11, 5.6), sharex=True)
    for col, (arm, color, label) in enumerate(
        (("metro", METRO_C, "Classical MH"), ("quantum", QUANTUM_C, "QeMCMC"))
    ):
        e_tr = p["arms"][arm]["energy_traces"]
        m_tr = p["arms"][arm]["mag_traces"]
        for tr in e_tr:
            axes[0, col].plot(tr, color=color, lw=0.8, alpha=0.75)
        for tr in m_tr:
            axes[1, col].plot(tr, color=color, lw=0.8, alpha=0.75)
        axes[0, col].set_title(f"{label}: energy", fontsize=10)
        axes[1, col].set_title(f"{label}: magnetization", fontsize=10)
        if p.get("exact"):
            axes[0, col].axhline(p["exact"]["energy"], color=EXACT_C, ls="--", lw=1.1)
    axes[1, 0].set_ylabel("magnetization")
    axes[0, 0].set_ylabel("energy")
    for ax in axes[1]:
        ax.set_xlabel("chain step (downsampled)")
    fig.suptitle(f"{p['spec']['title']}: chain traces "
                 f"(dashed = exact Boltzmann energy)", fontsize=11)
    _show(fig, live)


def fig_flips(p, live=False):
    """Proposal moves: how many spins change per accepted move."""
    import matplotlib.pyplot as plt
    n = len(p["tiers"])
    xs = np.arange(n + 1)
    width = 0.8 / 2
    fig, ax = plt.subplots(figsize=(7, 3.6))
    for i, (arm, color, label) in enumerate(
        (("metro", METRO_C, "Classical MH"), ("quantum", QUANTUM_C, "QeMCMC"))
    ):
        h = np.asarray(p["arms"][arm]["flip_hist"], float)
        h = h / h.sum() * 100
        ax.bar(xs + (i - 0.5) * width, h, width, color=color, label=label)
    ax.set_xticks(xs)
    ax.set_xlabel("spins flipped in one accepted move")
    ax.set_ylabel("% of accepted moves")
    ax.set_yscale("log")
    ax.legend(fontsize=8, frameon=False)
    ax.set_title(f"{p['spec']['title']}: accepted-move flip sizes\n"
                 f"the quantum proposal flips whole regions", fontsize=10)
    _show(fig, live)


def fig_convergence(p, live=False):
    """Time-to-accuracy ladder: rho and chi relerr vs chain length."""
    import matplotlib.pyplot as plt
    conv = p.get("convergence")
    if conv is None:
        return None
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 3.8))
    for arm, color, label in (("metro", METRO_C, "Classical MH"),
                              ("quantum", QUANTUM_C, "QeMCMC")):
        pts = conv["curves"][arm]
        steps = [c["steps"] for c in pts]
        ax1.plot(steps, [c["mu_spearman"] for c in pts], "o-", color=color, label=label)
        ax2.plot(steps, [c["chi_relerr"] for c in pts], "s-", color=color, label=label)
    ax1.axhline(0.9, color="grey", lw=0.8, ls="--")
    ax1.set_ylim(-1.05, 1.05)
    ax1.set_ylabel(r"Spearman $\rho$ vs exact $\chi$")
    ax1.set_title("When does the ranking become correct?", fontsize=10)
    ax2.axhline(0.1, color="grey", lw=0.8, ls="--")
    ax2.set_yscale("log")
    ax2.set_ylabel(r"relative error of $\chi$")
    ax2.set_title("How far off are the susceptibilities?", fontsize=10)
    for ax in (ax1, ax2):
        ax.set_xlabel("chain length (steps)")
        ax.legend(fontsize=8, frameon=False)
    q, m = steps_to_good(conv["curves"]["quantum"]), steps_to_good(conv["curves"]["metro"])
    fig.suptitle(f"{p['spec']['title']}: time-to-accuracy  (QeMCMC {fmt_steps(q)} "
                 f"vs classical {fmt_steps(m)} steps to a correct ranking)",
                 fontsize=11)
    _show(fig, live)
    return q, m


def fig_ranking(p, live=False):
    """mu_j bars: exact vs both samplers vs structural baselines."""
    import matplotlib.pyplot as plt
    n = len(p["tiers"])
    mu_exact = np.asarray(p["exact"]["chi"], float).mean(axis=0)
    order = np.argsort(-mu_exact)
    cols = [("exact", mu_exact, EXACT_C),
            ("metro", p["arms"]["metro"]["mu"], METRO_C),
            ("quantum", p["arms"]["quantum"]["mu"], QUANTUM_C)]
    for name, scores in p["baselines"].items():
        cols.append((name, np.asarray(scores, float), BASE_COLORS.get(name, "#888")))
    width = 0.8 / len(cols)
    all_vals = [np.asarray(v, float) for _, v, _ in cols]
    scale = max(np.abs(all_vals).max(), 1e-9)
    centers = np.arange(n)
    fig, ax = plt.subplots(figsize=(8, 4))
    for i, (name, vals, color) in enumerate(cols):
        v = np.asarray(vals, float)[order] / scale
        ax.bar(centers + (i - (len(cols) - 1) / 2) * width,
               v, width, label=name, color=color)
    ax.set_xticks(centers)
    ax.set_xticklabels([f"{i} {p['tiers'][i]}" for i in order], fontsize=7,
                       rotation=45)
    ax.set_ylabel(r"$\mu_j$ (normalised)")
    ax.legend(fontsize=7, frameon=False, ncol=3)
    ax.set_title(f"{p['spec']['title']}: bailout ranking -- exact vs samplers vs "
                 f"structural baselines", fontsize=10)
    _show(fig, live)


def fig_regret(p, live=False):
    """Regret per budget: static top-K (bars) + sequential policy (steps)."""
    import matplotlib.pyplot as plt
    itv = p["intervention"]
    budget = p["spec"]["budget"]
    ks = [str(k) for k in range(1, budget + 1)]
    static = [r for r in ("metro", "quantum", "strength", "load", "eigenvector", "debtrank")
              if r in itv["static_table"]]
    seq = ["exact-seq", "metro-seq", "quantum-seq"]

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4))
    x = np.arange(len(ks))
    width = 0.8 / len(static)
    for i, r in enumerate(static):
        vals = [itv["static_table"][r][k]["regret"] or 0.0 for k in ks]
        color = (METRO_C if r == "metro" else QUANTUM_C if r == "quantum"
                 else BASE_COLORS.get(r, "#888"))
        ax1.bar(x + (i - (len(static) - 1) / 2) * width, vals, width,
                label=r, color=color)
    ax1.set_xticks(x)
    ax1.set_xticklabels([f"K={k}" for k in ks])
    ax1.set_ylabel("regret vs exact optimum")
    ax1.set_title("static top-K policy", fontsize=10)
    ax1.legend(fontsize=7, frameon=False)

    offsets = {"exact-seq": 0.0, "metro-seq": -0.05, "quantum-seq": 0.05}
    for name, color, marker in (("exact-seq", EXACT_C, "D"),
                                ("metro-seq", METRO_C, "o"),
                                ("quantum-seq", QUANTUM_C, "s")):
        vals = [itv["sequential_table"][name][k]["regret"] or 0.0 for k in ks]
        ax2.plot(x + offsets[name], vals, marker + "-", color=color, label=name,
                 lw=1.4, ms=5, alpha=0.9)
        if all(
            itv["sequential_table"][name][k]["set"] == itv["sequential_table"]["exact-seq"][k]["set"]
            for k in ks
        ):
            ax2.annotate("same doses as exact", (x[-1], vals[-1]),
                         xytext=(-8, -14), textcoords="offset points",
                         ha="right", fontsize=7, color="#555")
    ax2.axhline(0, color="grey", lw=0.6)
    ax2.set_xticks(x)
    ax2.set_xticklabels([f"K={k}" for k in ks])
    ax2.set_title("sequential (re-ranked per dose) policy", fontsize=10)
    ax2.set_ylabel("regret vs exact optimum")
    ax2.legend(fontsize=8, frameon=False)

    fig.suptitle(f"{p['spec']['title']}: cost of picking the wrong "
                 f"{'bailouts' if itv['kind'] == 'bailout' else 'widening targets'} "
                 f"(lower is better)", fontsize=11)
    _show(fig, live)


def print_fidelity(p):
    f, arms = p.get("fidelity", {}), p["arms"]
    spec = p["spec"]
    print(f"\n=== {spec['title']} ({spec['name']}) ===")
    print(scenario_story(spec["name"]))
    print(f"setup: n={spec.get('n') or len(p['tiers'])}, beta={spec['beta']}, "
          f"vuln={spec['vuln']}, frustration={spec.get('frustration', 0)}, "
          f"{spec['steps']:,} steps x {spec['chains']} chains")
    print(f"{'arm':>8} {'chi relerr':>10} {'mu spearman':>12} {'ESS/step':>9} "
          f"{'accept':>7} {'ms/step':>9} {'wall clock':>12}")
    for name, label in (("metro", "metro"), ("quantum", "quantum")):
        a = arms[name]
        fid = f.get(name, {})
        wall = f"{a['wall_clock_s'] / 60:.0f} min" if a["wall_clock_s"] > 120 \
            else f"{a['wall_clock_s']:.1f} s"
        print(f"{label:>8} {fid.get('chi_relerr', float('nan')):>10.3f} "
              f"{fid.get('mu_spearman', float('nan')):>12.3f} "
              f"{a['ess_per_step']:>9.4f} {a['acceptance']:>7.2f} "
              f"{a['ms_per_step']:>9.3f} {wall:>12}")
    print(f"verdict: {verdict(spec['name'])}")
    print(p["cost_note"])


def run_gallery(live=False):
    """All scenarios, all figures. live=True shortens nothing; it only
    flags the run as the live arm (used by main.py's outro)."""
    stories = load()
    summary = []
    for name in ("s1_conglomerate_core", "s2_hidden_amplifier",
                 "s3_rival_alliances", "s4_rush_hour"):
        p = stories[name]
        print_fidelity(p)
        fig_network(p, live)
        fig_basins(p, live)
        fig_traces(p, live)
        fig_flips(p, live)
        got = fig_convergence(p, live)
        fig_ranking(p, live)
        fig_regret(p, live)
        if got:
            summary.append((p, got[0], got[1]))
        print("-" * 72)

    _summary_figure(summary, live)
    print("\n" + HOW_TO_READ)
    for c in CAVEATS:
        print(f"  caveat: {c}")


def _summary_figure(summary, live=False):
    import matplotlib.pyplot as plt
    if not summary:
        return
    names = [p["spec"]["title"] for p, _, _ in summary]
    q = [g or 0 for _, g, _ in summary]
    m = [mg or 0 for _, _, mg in summary]
    y = np.arange(len(names))
    fig, ax = plt.subplots(figsize=(8, 0.6 * len(names) + 1.6))
    ax.barh(y + 0.2, m, 0.4, label="Classical MH", color=METRO_C)
    ax.barh(y - 0.2, q, 0.4, label="QeMCMC", color=QUANTUM_C)
    ax.set_yticks(y)
    ax.set_yticklabels(names)
    ax.invert_yaxis()
    ax.set_xlabel("steps per chain until the ranking is correct")
    ax.set_title("Time-to-accuracy across scenarios: steps until "
                 r"$\rho \geq 0.9$ and rel-err $\leq 0.1$", fontsize=11)
    hi = max(q + m) or 1
    ax.set_xlim(0, hi * 1.45)
    for yi, (qv, mv) in enumerate(zip(q, m)):
        ax.text(mv + hi * 0.015, yi + 0.2, f" {fmt_steps(mv if mv else None)}", va="center", fontsize=8)
        ax.text(qv + hi * 0.015, yi - 0.2, f" {fmt_steps(qv if qv else None)}", va="center", fontsize=8)
    ax.legend(loc="lower right", fontsize=9, frameon=False, bbox_to_anchor=(1.0, -0.02))
    _show(fig, live)