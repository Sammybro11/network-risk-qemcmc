"""Scenario gallery: every recorded showcase scenario rendered end-to-end.

Loads the compact digests in scenarios_data.py (generated by
experiments/export_scenario_digests.py) and, per scenario, produces:

  1. the network map with the exact susceptibility ranking overlay
  2. the basin histogram (both samplers vs exact) -- the two-moods story
  3. energy + magnetization traces per arm (stalling vs tunneling)
  4. accepted-move flip-size histograms (local hops vs multi-spin flips)
  5. convergence ladder: Spearman rho + chi relerr vs chain length
  6. mu ranking bars: exact vs metro vs quantum vs structural baselines
  7. regret at each budget K for static AND sequential policies
  8. the cost & fidelity table

Plus one cross-scenario summary figure (time-to-accuracy) at the end.
Every figure is plain matplotlib -> SVG on qollab, PNG locally.
"""

